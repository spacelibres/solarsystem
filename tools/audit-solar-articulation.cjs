const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const catalog = require(path.join(root, 'src/solar/config/catalog.generated.json'));
const craft = catalog.entries.filter(entry => entry.groups.includes('spacecraft'));
const counts = {};
for (const entry of craft) {
  for (const control of entry.controllers.filter(control => control.joint)) counts.align = (counts.align ?? 0) + 1;
  for (const control of entry.modelAnimations ?? []) counts[control.type] = (counts[control.type] ?? 0) + 1;
}
const controlled = craft.filter(entry => entry.controllers.some(control => control.joint) || entry.modelAnimations?.length);
const lines = [
  '# Spacecraft articulation inventory', '',
  'Generated by `node tools/audit-solar-articulation.cjs` from the statically compiled Eyes registrations. No recovered callback is executed.', '',
  `${craft.length} spacecraft registrations; ${controlled.length} contain explicit joint or model-visibility controls. The remaining ${craft.length-controlled.length} declare none of these model controls; whole-craft attitude and other mission controllers are separate.`, '',
  `Counts: ${Object.entries(counts).map(([type,count])=>`${type}=${count}`).join(', ')}.`, '',
  'This is source/configuration coverage, not an assertion that all dates and GPU pictures are identical. See [CPU comparison and mesh audit](joint-mesh-audit.md) and [runtime semantics](model-animation.md).', '',
  '| Spacecraft | Joint alignment | Model operations | Source |',
  '| --- | --- | --- | --- |',
];
for (const entry of craft) {
  const joints = entry.controllers.filter(control => control.joint).map(control=>control.joint).join(', ');
  const operations = (entry.modelAnimations ?? []).map(control=>`${control.type}: ${control.joint}`).join('; ');
  lines.push(`| ${entry.id} | ${joints || 'none declared'} | ${operations || 'none declared'} | ${entry.provenance.file}:${entry.provenance.line} |`);
}
const text = lines.join('\n') + '\n';
const output = path.join(root, 'docs/solar-system/articulation-inventory.md');
if (process.argv.includes('--check')) {
  if(fs.readFileSync(output,'utf8') !== text) throw Error('Articulation inventory is stale');
} else fs.writeFileSync(output, text);
console.log(JSON.stringify({spacecraft:craft.length,controlled:controlled.length,counts}));
