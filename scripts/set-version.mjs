#!/usr/bin/env node
/**
 * Set the project version everywhere it appears, in one step.
 *
 * Usage: node scripts/set-version.mjs <MAJOR.MINOR.PATCH>
 *
 * Updates:
 *   - package.json (and therefore package-lock.json via npm)
 *   - VERSION
 *   - src/lib/version.ts (consumed by the UI labels)
 *
 * It refuses to run with a malformed or non-increasing version so a genuinely
 * broken release cannot be produced by accident.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = process.argv[2];

if (!target || !/^\d+\.\d+\.\d+$/.test(target)) {
  console.error('usage: node scripts/set-version.mjs <MAJOR.MINOR.PATCH>');
  process.exit(1);
}

const versionFile = join(root, 'VERSION');
const current = readFileSync(versionFile, 'utf8').trim();

const parse = (v) => v.split('.').map(Number);
const cmp = (a, b) => {
  const [a1, a2, a3] = parse(a);
  const [b1, b2, b3] = parse(b);
  return a1 - b1 || a2 - b2 || a3 - b3;
};

if (cmp(target, current) <= 0) {
  console.error(`refusing to move version backwards: ${current} -> ${target}`);
  process.exit(1);
}

// package.json + package-lock.json
execFileSync('npm', ['version', target, '--no-git-tag-version', '--allow-same-version'], {
  cwd: root,
  stdio: 'inherit',
});

writeFileSync(versionFile, `${target}\n`);

const versionTs = join(root, 'src', 'lib', 'version.ts');
writeFileSync(
  versionTs,
  `/** Generated by scripts/set-version.mjs — do not edit by hand. */\nexport const VERSION = '${target}';\n`,
);

console.log(`version set: ${current} -> ${target}`);
